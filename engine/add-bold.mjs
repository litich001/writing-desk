/**
 * 给正文加 Markdown 粗体
 *
 * 用户要求：「有强调的内容，有一些重点，不然通篇下来都是长文」。
 * 这一篇 5000 多字，一个重点都没有，读者划到一半就停了。
 *
 * 加粗不是撒胡椒面，规则明确：
 *   1. 核心数字/年份 —— 「52岁」「77个」「21页」这类，读者要记住的
 *   2. 核心判断句    —— 段落里的那句结论，不是每句都加
 *   3. 关键原话      —— 他自己说的那几句
 * 目标密度：一篇 5000 字的稿子 20~30 处，每处都该有理由。
 *
 * 用脚本做而不是手改，为了：可复跑、可回滚、可验收。
 * 加粗标记写在脚本里，body.md 保持干净，改稿时重跑一次即可。
 */
