/**
 * 交给 AI 的活：构造任务词
 *
 * 分工原则（本项目最重要的架构决定）
 * ────────────────────────────────────────────
 *   本地代码  →  确定性的事：抓数据、排版、复制、存文件
 *   AI        →  需要理解的事：起标题、写摘要、提角度、核事实
 *
 * 之前标题建议是用字符串模板拼的（`${k(0)}背后…`、`quotes[0].slice(0,16)`），
 * 出来的是碎片和跟文章无关的固定文案 —— 用户原话「这太差劲了」。
 * 原因是模板填空做不到语义理解：它不知道这篇文章在讲什么。
 *
 * 所以这里不拼标题，只做一件事：把「当前正文 + 事实清单 + 风格 + 约束」
 * 整理成一段清楚的指令，让 AI 去做。人只需要复制粘贴。
 */

/** 稿子里的关键句 —— 给 AI 当锚点，不是标题 */
function keyLines(text, limit = 6) {
  return text
    .split(/\n+/)
    .map(s => s.replace(/^#{1,6}\s*/, '').replace(/\*\*/g, '').trim())
    .filter(s => s.length >= 12 && s.length <= 60)
    .filter(s => !/^[|>\-]/.test(s) && !/^!\[/.test(s))
    .filter(s => /[。！？]$/.test(s))
    .slice(0, limit)
}

/** 事实清单：已核实的和待核的分开，AI 才知道哪些能直接用 */
function factBlock(facts, limit = 12) {
  const all = Array.isArray(facts) ? facts : []
  const ok = all.filter(f => f.verdict === 'ok')
  const wait = all.filter(f => f.verdict !== 'ok')
  const pick = arr => arr.slice(0, limit).map(f => {
    const mark = f.verdict === 'ok' ? '已核实' : '待核'
    return `  · [${mark}] ${f.label}：${f.value}${f.ctx ? '（' + f.ctx + '）' : ''}`
  })
  const out = []
  if (ok.length) out.push('已核实的事实（直接用，不要改）：', ...pick(ok))
  if (wait.length) out.push('尚未核实的事实（慎用或避开）：', ...pick(wait))
  return out.length ? out.join('\n') : '（事实清单是空的，正文里的数字你自己判断可信度）'
}

/**
 * 出爆款标题的要求
 * @param {object} ctx {body, facts}
 * @param {object} st  {n, brief}
 */
export function titleTask(ctx, st) {
  const body = String(ctx.body || '')
  const chars = body.replace(/\s/g, '').length
  const outline = sectionOutline(body)
  return [
    '稿子已经写完了。现在通读全文，给标题。',
    '',
    `文风：${st.n || '你判断'}（${st.brief || '根据这篇稿子自己的调性'}）`,
    '',
    '读者是中老年人群，标题要一眼看懂、口语化，不要文艺。',
    '',
    '★ 最重要的一条：标题要基于【整篇文章】，不是基于某一个段落。',
    '',
    '  上一版给的一批标题全是「从某一段里摘一句原话」，',
    '  比如从开头摘「碗柜关不上」，从中间摘「每天煮一锅粥盛两碗」，',
    '  从后面摘「十九岁学泥匠」。这种标题读完全文只记得一个细节，',
    '  不知道整篇在说什么。',
    '',
    '  合格的样子：一个标题同时对得上文章【三个以上不同小节】的内容。',
    '  比如这篇文章有「房子的机理」和「人的处境」两条线，',
    '  标题就该落在两条线交叉的地方，而不是只讲一条线里的一个细节。',
    '',
    '  自检办法：把你写的每个标题拿去正文里找出处。',
    '  如果只能在一段里找到，那是摘句，重写。',
    '',
    '六个标题必须是六种【写法】，不是六个角度的同一句话。至少覆盖：',
    '  悬念式（留白，不把话说尽）',
    '  白描式（只摆具体物件，不讲道理）',
    '  人物式（从某个人切入）',
    '  数据式（有数字）',
    '  结论式（把机理收成一句判断）',
    '  对照式（两件事并排放）',
    '',
    '「写法」和「方向」是两件事，两个都要：',
    '  写法 = 用什么句式（上面那六种）',
    '  方向 = 落在文章哪一块（房子的机理 / 人的处境 / 两者交叉的地方）',
    '  只换写法不换方向，就成了六个角度的同一句话。',
    '',
    '其余硬要求：',
    '1. 长度 14~28 字，手机上一行能看完',
    '   （概括性标题要盖住多个小节，本来就长一点，12 字上限太紧）',
    '2. 不要写放之四海皆准的万能句 —— 那种句子换成任何一篇文章都成立，等于没标题',
    '   「窗台那盆花早死了」「时间会证明一切」都是这种。',
    '   概括性标题越长越容易犯这个毛病：为了显得全面就往里塞抽象词。',
    '3. 用正文里真实出现的事实、数字、人物，不要编',
    '4. 不要出现「本文」「我们来看」「揭秘」这类词',
    '5. 不要用双引号把整句包起来',
    '6. 不要写「先说结论」「免得有人误解」这类预设',
    '7. 不要写「不是A而是B」「没有A只有B」，标题是最短的地方，最容易被判死',
    '',
    '给我 6 个完整标题，按推荐顺序排，最能打的放第一个。',
    '每个后面用括号写清楚：这个标题对应正文哪几节、为什么这个角度成立。',
    '',
    '─────── 正文（' + chars + ' 字）───────',
    body.trim(),
    '',
    '─────── 这篇稿子的小节（判断标题要覆盖哪几节用）───────',
    outline,
    '',
    '─────── 事实清单 ───────',
    factBlock(ctx.facts),
    '',
    '─────── 稿子里的关键句（供你判断主线，不是让你直接抄）───────',
    keyLines(body).map(s => '  ' + s).join('\n')
  ].join('\n')
}

/**
 * 列出正文的小节结构。
 *
 * ★ 为什么加这个：AI 拿一整篇三千字，容易只盯着开头两段和某一段细节。
 *   把小节清单摆在要求里，它才会想到「这个标题要盖住哪几节」。
 *   上一版给的六条标题全是单段摘句，就是因为清单没摆出来。
 */
function sectionOutline(body) {
  const out = []
  const lines = String(body || '').split('\n')
  lines.forEach((l, i) => {
    const m = l.match(/^##\s*(.+)$/)
    if (!m) return
    /* 数一下这一节到下一节有多少字，AI 才知道哪几节是重点 */
    let chars = 0
    for (let k = i + 1; k < lines.length; k++) {
      if (/^##\s/.test(lines[k])) break
      if (/^---/.test(lines[k])) break
      chars += lines[k].replace(/\s/g, '').length
    }
    out.push('  ' + m[1] + '（' + chars + ' 字）')
  })
  return out.length ? out.join('\n') : '  （这篇稿子没有分小节）'
}

/** 出摘要（公众号那 120 字）的要求 */
export function abstractTask(ctx) {
  const body = String(ctx.body || '')
  return [
    '给这篇稿子写公众号摘要。',
    '',
    '硬要求：',
    '1. 120 字以内',
    '2. 第一句就要让人想点开，不要写「本文讲述」「最近有这样一个事」这种开场',
    '3. 用具体的数字或事实，不要空泛的形容词',
    '4. 结尾不要升华，不要「值得深思」「引发热议」',
    '5. 只给 3 版，让我挑',
    '',
    '─────── 正文（' + body.replace(/\s/g, '').length + ' 字）───────',
    body.trim(),
    '',
    '─────── 事实清单 ───────',
    factBlock(ctx.facts)
  ].join('\n')
}

/** 提切入角度的要求（热点页用） */
export function angleTask(ctx, title, summary) {
  return [
    `我要写「${title}」这个题，给我 5 个不同的切入角度。`,
    '',
    summary ? '这条的摘要：\n' + summary : '',
    '硬要求：',
    '1. 每个角度是一句话，说清楚「我要从哪个角度切，为什么别人没这么切」',
    '2. 5 个角度必须是不同的方向，不能都是「分析原因」',
    '3. 不要写「可以从以下几个方面」这种废话',
    '4. 其中至少 2 个是反常识的（大部分人以为 A，其实不是 A）',
    '5. 避开会写烂的角度（已经被写烂的那种）',
    '',
    '每个角度后面标一个括号，写清楚「写出来大概是什么样子」。'
  ].filter(Boolean).join('\n')
}