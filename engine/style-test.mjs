let bad = 0
const ck = (n, c, e) => {
  console.log('  ' + (c ? '✓ ' : '✗ ') + n + (e ? '  ' + e : ''))
  if (!c) bad++
}

console.log('\n  风格对抗验收')
console.log('  ' + '-'.repeat(66))

/* ── 1. 负样本必须被判不合格 ── */
console.log('\n  【1】负样本：这些必须被抓出来')
/* expectClean 的样本是「必须判干净」的 ——
   图注的「出处：」和直接引语前的「她说的是：」是用户明确要求保留的，
   白名单要是没生效，这里会红。 */
let cleanFail = 0
for (const s of NEG) {
  const r = aiSmell(s.text)
  if (s.expectClean) {
    const okc = r.hits.length === 0
    if (!okc) cleanFail++
    ck('白名单放行「' + s.name.replace('__ok_', '') + '」', okc,
      okc ? '' : '被误判：' + r.hits.map(h => h.n + '(' + h.sample + ')').slice(0, 3).join('，'))
  } else {
    ck('抓到「' + s.name + '」', r.hits.length > 0,
      r.hits.length ? r.hits.map(h => h.n).slice(0, 3).join('，') : '竟然没抓到')
  }
}
ck('白名单没有误伤（出处：和直接引语必须放行）', cleanFail === 0, cleanFail + ' 个被误判')

/* ── 2. 每种风格的正样本必须全过 ── */
console.log('\n  【2】正样本：每种风格必须全项通过')
for (const id of Object.keys(STYLES)) {
  const text = POS[id]
  if (!text) { ck(STYLES[id].n + ' 有正样本', false, '缺样本'); continue }
  const r = checkStyle(text, id)
  ck(STYLES[id].n, r.pass, r.verdict + '（' + r.prefers.map(p => p.n + ' ' + p.v + '/' + p.target).join('，') + '）')
}

/* ── 3. 交叉：A 风格的样本不该被 B 风格判过（要有区分度）───────── */
console.log('\n  【3】交叉：风格之间要有区分度（拿 A 考 B，该不过）')
const ids = Object.keys(STYLES)
let crossMiss = 0, crossTotal = 0
for (const a of ids) {
  for (const b of ids) {
    if (a === b) continue
    crossTotal++
    const r = checkStyle(POS[a], b)
    if (r.pass) {
      crossMiss++
      if (crossMiss <= 3) console.log('      · ' + STYLES[a].n + '的样本也过了' + STYLES[b].n)
    }
  }
}
ck('交叉区分度：不同风格不会互相误判为通过',
  crossMiss / crossTotal < 0.3,
  crossTotal + ' 组里错了 ' + crossMiss + ' 组（' + Math.round(crossMiss / crossTotal * 100) + '%）')

/* ── 4. 每种风格的硬禁不能被正样本触发 ── */
console.log('\n  【4】各风格硬禁规则自检')
for (const id of ids) {
  const r = checkStyle(POS[id], id)
  ck(STYLES[id].n + ' 不触自己的硬禁', r.forbids.length === 0,
    r.forbids.map(f => f.n).join('，'))
}

console.log('  ' + '-'.repeat(66))
console.log(bad === 0 ? '  全部通过\n' : '  ' + bad + ' 项失败\n')
process.exit(bad ? 1 : 0)
