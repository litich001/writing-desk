import { aiSmell, aiSmell as _ } from './styles.mjs'

/* 我这一轮从正文里删掉的每一句，都拿回来喂给判据。
   如果判据抓不到，说明「改稿」和「改判据」是两件没接上的事 ——
   下次 AI 再写一遍还是会被放过。

   ★ 这就是「删掉的句子要当负样本」的道理：
     正样本只能证明「现在这版是好的」，
     负样本才能证明「以后再犯会被抓」。 */

const MUST_CATCH = [
  ['小节标题·提前否定', '## 四、有人会说这是幸存者偏差\n\n肯定有人说。\n\n这就是幸存者偏差。'],
  ['小节标题·元标题', '## 十五、结尾\n\n我最后说一件事。'],
  ['小节标题·预告式', '## 九、说点不好听的\n\n这事儿传到今天已经变成鸡汤了。'],
  ['小节标题·双重否定', '## 十三、别学她，也别不信她\n\n她的情况很特殊。'],
  ['小节标题·标题内否定', '## 五、她自己的总结，不是「我战胜了癌症」\n\n我特别留意了一下。'],
  ['自我预设', '写这篇的时候我最怕的就是写成「心态好能治病」。\n\n真的不能。'],
  ['预先否掉没人说的话', '她没说「我战胜了癌症」。没说「心态好了病就好了」。\n\n她说的是另一段话。'],
  ['不是A而是B·她是', '她大概不是「不管了」，她是「不想就这么等着」。'],
  ['不是A而是B·是那个', '一个刚拿到诊断的人，最难受的不是病，是那个「等着」。'],
  ['不是A而是B·是「我想去」', '她的第一反应不是「完了」，是「我想去南极」。'],
  ['不是A而是B·是两种', '这不是运气，这是她在那儿待住了。'],
  ['否定式收尾·没关系', '你听听，这跟治病没关系。'],
  ['否定式收尾·一点关系都没有', '「不计较」这三个字，跟肿瘤一点关系都没有。'],
  ['否定式收尾·不是治愈', '她的原话是「可以继续观察」。观察不是治愈。'],
  ['否定式收尾·不是运气', '那不是「运气好」，那是她知道自己要什么。']
]

/* 这些必须放行 —— 白名单误伤同样是 bug */
const MUST_PASS = [
  ['图注长', '![图：王英在野外架着长焦相机。图/云南广播电视台 YNTV2《都市条形码》](jz_1.png)'],
  ['图注短', '![图：王英在野外拍摄象海豹](jz_2.png)'],
  ['来源表', '| 云南广播电视台 YNTV2《都市条形码》 | 原始报道：退休前查出甲状腺癌 | 2026-10-01 |'],
  ['出处单独一行', '出处：南极科考站提供'],
  ['直接引语', '她的原话是：这事我不问了。'],
  ['新写的小节标题', '## 四、南极没治好的人不会拍视频\n\n去南极没治好的人不会拍视频。\n\n她被问到这件事的时候，说的是这么一段。']
]

let bad = 0
console.log('=== 必须抓到 ===')
for (const [n, t] of MUST_CATCH) {
  const r = aiSmell(t)
  const ok = r.hits.length > 0
  if (!ok) bad++
  console.log((ok ? '  OK  ' : '  BAD ') + n + (ok ? '  <- ' + r.hits.map(h => h.n).join('，') : '  ★ 竟然放行了'))
}

console.log('')
console.log('=== 必须放行 ===')
for (const [n, t] of MUST_PASS) {
  const r = aiSmell(t)
  const ok = r.hits.length === 0
  if (!ok) bad++
  console.log((ok ? '  OK  ' : '  BAD ') + n + (ok ? '' : '  误伤: ' + r.hits.map(h => h.n + '(' + h.sample + ')').join('，')))
}

console.log('')
console.log(bad ? bad + ' 条不符' : '全部正确')
process.exit(bad ? 1 : 0)