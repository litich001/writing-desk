/**
 * 排版内核单测：中文书名号 + 加粗
 *
 * 为什么要有这个（实测踩到的坑）：
 *   `按**《消费者权益保护法》第五十五条**处理。` 渲染不出来，
 *   两个星号原样留在正文里 —— 读者看到的是「按**《消法》第五十五条**处理」。
 *
 * 规律是逐个测出来的，不是猜的：
 *   `**第五十五条**`           正常
 *   `**《消法》第五十五条**`   行首正常
 *   `按**《消法》第五十五条**` 失败 ← 前面有中文就挂
 *
 * 原因：markdown-it 的 emphasis 左侧规则里 `《` 算标点，
 * `**` 后面紧跟标点会被判成「不是左边界」，整个配对失败。
 *
 * 修法（见 layout.mjs）：在分词前把 `《` 挪到加粗外面。
 * 注意必须在 normalize 之前做 —— 写在 core.ruler 里（分词之后）不生效，踩过。
 */
import { preview } from './layout.mjs'

let bad = 0
const ok = (n, c, e) => {
  console.log('  ' + (c ? 'PASS  ' : 'FAIL  ') + n + (e ? '   ' + e : ''))
  if (!c) bad++
}

console.log('\n  排版内核单测：中文书名号 + 加粗')
console.log('  ' + '-'.repeat(62))

const render = async (t) => {
  const r = await preview(t, 'plain', [])
  return r.body || ''
}

/* ---------- 1. 原始失败场景（这是本测试存在的理由）---------- */
const cases = [
  // 前置中文 —— 原来会挂
  ['按**《消法》第五十五条**处理。', '最常见的形态：正文里引用法条'],
  ['诉求明确：按**《消费者权益保护法》第五十五条**处理。', '带前缀的引用'],
  ['依据**《市场监督管理投诉举报处理办法》第十七条**判断。', '长法条名'],

  // 行首 —— 原来就正常，改完不能被改坏
  ['**《消法》第五十五条**', '行首形态不能被改坏'],
  ['**《消法》第五十五条**。', '行首带句号'],
  ['**《消法》第五十五条**处理。', '行首带后文'],

  // 加粗里只有书名号（病态但会遇到）
  ['**《消法》**处理', '加粗里只有一个书名号'],
  ['**《消法》**和**《广告法》**都提到了', '两个书名号连用'],

  // 不含书名号 —— 绝对不能被影响
  ['**第五十五条**处理', '普通加粗'],
  ['诉求明确：**退一赔三**。', '句中加粗'],
  ['普通文本没有加粗', '无加粗'],
  ['## 二、**退一赔三**被当成公式用了', '标题里的加粗'],

  // 图后面的加粗
  ['看图 ![x](y.jpg) 后的文字 **《广告法》第三十八条**处理', '图片后的书名号加粗'],

  // 已经是正确写法的（不能被改坏）
  ['《消法》**第五十五条**已经正常', '本来就在加粗外的书名号']
]

for (const [text, why] of cases) {
  const html = await render(text)
  const wantStrong = /strong/.test(text)
  const gotStrong = /<strong>/.test(html)
  const leftover = (html.match(/\*\*/g) || []).length
  const pass = (wantStrong ? gotStrong : true) && leftover === 0
  ok(why || text, pass,
    pass ? '' : '→ ' + html.replace(/<\/?section>/g, '').slice(0, 70))
}

/* ---------- 2. 输出里不能有零宽字符残留 ---------- */
const zw = await render('按**《消法》第五十五条**处理。')
ok('输出无零宽字符（U+200B/2060）', !/[\u200B\u2060\uFEFF]/.test(zw))
ok('输出无字面星号', !/\*\*/.test(zw))

/* ---------- 3. 加粗内容保持原样 ---------- */
const h2 = await render('按**《消费者权益保护法》第五十五条**处理。')
ok('书名号内容完整保留', h2.includes('消费者权益保护法') && h2.includes('第五十五条'))
ok('书名号符号保留', h2.includes('《') && h2.includes('》'))
/* 视觉上有一个妥协要说清：
   原本想让「《书名》内容」整体加粗，但 markdown-it 认不了这个形态。
   修法是把《》留在加粗外、内容加粗内。
   差别只在书名号那两个符号是不是粗体 —— 文字内容照样加粗。
   这比留着两个星号在正文里强得多。 */
ok('内容加粗、书名号留在加粗外（明确的视觉妥协）',
  /按《消费者权益保护法》<strong>第五十五条<\/strong>处理/.test(h2),
  h2.replace(/<\/?section>/g, '').slice(0, 90))
ok('★ 内容部分确实被加粗了（不是把整段降级）',
  /<strong>第五十五条<\/strong>/.test(h2))

console.log('  ' + '-'.repeat(62))
console.log(bad === 0 ? '  全部通过\n' : '  ' + bad + ' 项失败\n')
process.exit(bad ? 1 : 0)