/** 基础 AI 味检测，任何风格都跑这一套 */
export function aiSmell(text) {
  const hits = []
  for (const s of AI_SMELL) {
    const m = text.match(s.re)
    if (m) hits.push({ n: s.n, n_hit: m.length, sample: m[0] })
  }
  /* 破折号：以前一律算 AI 味，实测把商业稿、评论稿的好句子判死了。
     破折号本身是正常中文用法，只有「用得密」才可疑 ——
     判据改成密度：每 100 字超过 1.5 个才算 AI 味。
     （第一版按「文本 <300 字就罚」也不对：短评本来就短，一个破折号很正常。） */
  const len = text.replace(/\s/g, '').length
  const dash = (text.match(/——/g) || []).length
  if (len > 0 && dash / (len / 100) > 1.5) {
    hits.push({ n: '破折号过密', n_hit: dash, sample: '每百字 ' + (dash / (len / 100)).toFixed(1) + ' 个' })
  }
  /* ── 三组共享禁令（9 种风格全部生效）──
     加在这里而不是塞进 STYLES 的 forbid：
     塞九遍必然漏一处，而且改规则要改九处。
     aiSmell 是通用层，放一次全继承。 */
  for (const b of sharedBans()) {
    /* 标点要先过白名单 —— 图注的「出处：」不算。 */
    let re = b.re
    if (b.n === '双引号' || b.n === '破折号' || b.n === '冒号') {
      const raw = text
      if (b.n === '冒号') {
        /* 冒号逐个判：先摘掉白名单位置，再数剩下的 */
        const masked = raw.replace(PUNCT_OK, (m) => ' '.repeat(m.length))
        const mm = masked.match(re)
        if (mm) hits.push({ n: b.n + '（排除出处后）', n_hit: mm.length, sample: mm[0], lv: 'hi' })
        continue
      }
      re = new RegExp(b.re.source, b.re.flags)
    }
    const m = text.match(re)
    if (m) hits.push({ n: b.n, n_hit: m.length, sample: m[0], lv: 'hi' })
  }

  // 段落长度均匀度：真人写作段落长短不一，AI 很整齐
  const paras = text.split(/\n\s*\n/).map(p => p.trim()).filter(p => p.length > 20)
  let uniformity = 0
  if (paras.length >= 5) {
    const l = paras.map(p => p.length)
    const avg = l.reduce((a, b) => a + b, 0) / l.length
    const sd = Math.sqrt(l.reduce((a, b) => a + (b - avg) ** 2, 0) / l.length) / avg
    uniformity = sd
    if (sd < 0.22) hits.push({ n: '段落过于均匀', n_hit: paras.length, sample: '标准差 ' + sd.toFixed(3) })
  }
  return { hits, uniformity, paraCount: paras.length }
}

