/* 短句占比：≤15 字算短句 */
function shortRatio(t) {
  const sents = t.split(/[。！？\n]/).map(s => s.trim()).filter(s => s.length > 2)
  if (!sents.length) return 0
  return sents.filter(s => s.length <= 15).length / sents.length
}

/**
 * 跑一遍风格验收。
 * @returns { style, pass, aiHits, forbids, requires, prefers, score, verdict }
 */
export function checkStyle(text, styleId) {
  const st = STYLES[styleId]
  if (!st) return { style: styleId, pass: false, verdict: '未知风格' }

  const ai = aiSmell(text)

  const forbids = st.forbid.map(f => {
    const m = text.match(f.re)
    return { n: f.n, hit: !!m, n_hit: m ? m.length : 0, why: f.why }
  }).filter(f => f.hit)

  const requires = st.require.map(r => {
    const ok = r.re.test(text)
    return { n: r.n, ok, why: r.why }
  }).filter(r => !r.ok)

  const prefers = st.prefer.map(p => {
    const v = p.fn(text)
    return { n: p.n, v: Number(v.toFixed(3)), target: p.good, why: p.why }
  })

  // 评分：AI 味扣分 + 硬禁重罚 + 偏好加分
  let score = 100
  score -= ai.hits.reduce((a, h) => a + (h.n === '段落过于均匀' ? 12 : 6), 0)
  score -= forbids.length * 20
  score -= requires.length * 10
  for (const p of prefers) {
    const ratio = p.target > 0 ? Math.min(1, p.v / p.target) : 0
    score += Math.round(ratio * 8) - 8   // 每项最多 +8，达不到就扣
  }
  score = Math.max(0, Math.min(100, score))

  /* 标点硬禁独立成项：原来按密度判（per100），
     一篇 4000 字的稿子有 40 个破折号也才 1/千字，密度规则根本不响。
     用户原话「不许用双引号、破折号、冒号」是硬要求，不是建议。 */
  const punctHits = ai.hits.filter(h => /双引号|破折号|冒号/.test(h.n))

  const pass = ai.hits.length === 0 && forbids.length === 0 && requires.length === 0

  /* 三组共享禁令单独报出来，让界面能说清「为什么不过」 */
  const shared = ai.hits.filter(h =>
    h.lv === 'hi' && /双引号|破折号|冒号|不是A而是B|没有A只有B|既不也不|不也不|双重否定|全称否定|假装共识|主观预设|替读者划边界|集体主语/.test(h.n)
  )

  return {
    style: styleId,
    styleName: st.n,
    pass,
    score,
    punctHits,
    shared,
    aiHits: ai.hits,
    forbids,
    requires,
    prefers,
    uniformity: Number(ai.uniformity.toFixed(3)),
    verdict: pass
      ? `通过（${score} 分）`
      : [
          punctHits.length ? `标点硬禁 ${punctHits.length} 类` : '',
          shared.length ? `共享禁令 ${shared.length} 类` : '',
          ai.hits.length ? `AI 味 ${ai.hits.length} 处` : '',
          forbids.length ? `硬禁 ${forbids.length} 处` : '',
          requires.length ? `必备缺失 ${requires.length} 项` : ''
        ].filter(Boolean).join('，')
  }
}
