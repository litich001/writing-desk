/* ---------- 常量（必须在这里，不能往下放）----------
   模块顶部的 const 有暂时性死区：
   声明在后面的常量，被前面的代码引用时直接抛
   「Cannot access X before initialization」，整个模块加载失败。
   PUNCT_BAN 在文件中间引用 DASH_RE，所以 DASH_RE 必须更早。 */

/* 破折号：只管中文标点，不管 markdown 语法。
   --- 是分隔线，|---|---| 是表格分隔行，两者都不是标点。
   负向前后顾能把它们排除，又不漏掉正文里的单破折号。 */
export const DASH_RE = /——|(?<!-)--(?!-)/g

/* 标点白名单：命中即放过这一处。
   单独抽出来是因为它要给两套判据共用（styles.mjs 和 app.js），
   两处不一致的后果是「界面上过了、服务端判不过」，
   用户改到崩溃也找不到原因。

   覆盖六种合法用法：
     一  图注里的「图：」「照片：」
     二  来源表的「出处：」「来源：」「图注：」「备注：」
     三  表格单元格里的冒号（| 原始报道：xxx |）
     四  直接引语前的「她说的是：」「她的原话是：」「原话：」
   漏过一次就补不回来，加新类型前先跑 style-test.mjs 的白名单用例。 */
export const PUNCT_OK = /((^|\n)\s*[-*|>]*\s*(出处|来源|图注|备注|题注)[：：][^\n]{0,120}|((图|图表|图片|照片)[：：][^()\n]{0,140})|((原话|她说|他说|原话是)[^\n：:]{0,8}[：：])|(\|[^\n|]{0,24}[：：][^\n|]{0,60}\|)|(\|[^\n]{0,300}[：：][^\n]{0,300}\|[^\n]{0,300}\|))/g


