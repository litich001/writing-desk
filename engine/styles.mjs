/* ── 三组禁令的合并入口 ──
   checkStyle 里用这个，不能各处各写一遍（写三遍必然漏一处）。 */
export function sharedBans() {
  return [...PUNCT_BAN, ...NEGATION_BAN, ...PRESET_BAN].filter(r => !r.skip)
}


